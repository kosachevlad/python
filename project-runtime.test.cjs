const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {Project}=require('./project-store.js');
const {Runtime}=require('./project-runtime.js');
const dir=process.env.PYODIDE_DIR||path.resolve(__dirname,'../turtle/pyodide');
const {loadPyodide}=require(path.join(dir,'pyodide.js'));
globalThis.kodikProjectInput=()=> '7';
(async()=>{
const py=await loadPyodide({indexURL:dir+path.sep}),r=new Runtime(py,fs.readFileSync(path.join(__dirname,'project-runtime.py'),'utf8'));
const p=Project.empty('Тест');
p.create('main.py','file','from helper import VALUE\nfrom pathlib import Path\nprint(VALUE, Path("data/input.txt").read_text())\nPath("output.txt").write_text("готово")\n');
p.create('helper.py','file','VALUE=10');
p.create('data/input.txt','file','Привіт');
p.create('keep.pyc','file','AAEC','base64');
p.state.openIds=[p.at('main.py').id];p.state.activeId=p.at('main.py').id;
r.write(p);
assert.match(await r.execute(p.at('main.py').content,'main.py'),/10 Привіт/);
assert(r.capture(p).changed);assert(p.at('keep.pyc'));assert.equal(p.at('output.txt').content,'готово');assert.equal(p.state.activeId,p.at('main.py').id);
p.update(p.at('helper.py').id,'VALUE=20');
r.write(p);assert.match(await r.execute(p.at('main.py').content,'main.py'),/20 Привіт/);
await r.execute('import os\nos.remove("data/input.txt")\nos.makedirs("generated",exist_ok=True)\nopen("generated/binary.bin","wb").write(bytes([0,255,10]))\n','main.py');
r.capture(p);assert(!p.at('data/input.txt'));assert.equal(p.at('generated/binary.bin').encoding,'base64');
r.write(p);
await r.execute('open("output.txt","w").write("python")','main.py');
p.update(p.at('output.txt').id,'editor');
const result=r.capture(p);assert.equal(result.conflicts.length,1);assert.equal(p.at('output.txt').content,'editor');assert.equal(p.at(result.conflicts[0]).content,'python');
r.write(p);
py.FS.writeFile('/home/pyodide/keep.txt','untouched');
await r.execute('import os\nos.symlink("/home/pyodide/keep.txt","link.txt")','main.py');
r.capture(p);assert(!p.at('link.txt'));r.write(p);assert.equal(py.FS.readFile('/home/pyodide/keep.txt',{encoding:'utf8'}),'untouched');
assert.match(await r.execute('print(input("Число: "))','main.py'),/7/);
assert.match(await r.execute('print(__file__)\nraise ValueError("тест")','scripts/test.py'),/scripts\/test.py/);
assert.match(await r.execute('print("ok")','main.py'),/ok/);
await r.execute('import os\nos.chdir("generated")','main.py');r.write(p);
r.leave();assert.equal(py.runPython('import os\nos.getcwd()'),'/home/pyodide');
console.log('PASS: real Python module imports, cache invalidation, data I/O, generated files, binary files, edit conflicts, symlinks, nested scripts, input, tracebacks, repeated runs and cwd restoration.');
})().catch(error=>{console.error(error);process.exitCode=1});
